#!/usr/bin/env node
// Generate src/lib/protocol.gen.ts from ../backend/protocol.schema.json (the backend's pydantic models are the
// single source of truth).
//
//   node scripts/gen-protocol.mjs           # (re)write src/lib/protocol.gen.ts
//   node scripts/gen-protocol.mjs --check   # exit 1 if the committed file is stale (drift gate)
//
// The schema is normalised before json-schema-to-typescript sees it, so the output is small and stable:
// - the four root unions (client/server events, worker IPC) become named $defs (ClientEvent, ServerEvent, ...);
// - `title` is dropped everywhere except on named definitions (json2ts otherwise emits an alias per property);
// - JSON Schema 2020-12 tuples (`prefixItems`) are rewritten to the draft-07 form json2ts understands;
// - OpenAPI-style `discriminator` hints are dropped (unions narrow on the required `type`/`kind` const instead).
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, relative, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { compile } from 'json-schema-to-typescript';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const schemaPath = resolve(root, '../backend/protocol.schema.json');
const outPath = resolve(root, 'src/lib/protocol.gen.ts');

const ROOT_UNIONS = {
  client: 'ClientEvent',
  server: 'ServerEvent',
  worker_command: 'WorkerCommand',
  worker_event: 'WorkerEvent',
};

const BANNER = [
  '/* eslint-disable */',
  '// DO NOT EDIT. Generated by `npm run gen:protocol` from backend/protocol.schema.json.',
  '// Source of truth: backend/src/clicky/protocol/*.py. `npm run gen:protocol:check` fails on drift.',
].join('\n');

/** Recursively normalise one subschema (see the header comment). `keepTitle` is true only for named definitions. */
function normalise(node, keepTitle = false) {
  if (Array.isArray(node)) return node.map((item) => normalise(item));
  if (node === null || typeof node !== 'object') return node;
  const out = {};
  for (const [key, value] of Object.entries(node)) {
    if (key === 'discriminator') continue;
    if (key === 'title' && !keepTitle) continue;
    if (key === '$defs') {
      out.$defs = Object.fromEntries(Object.entries(value).map(([name, def]) => [name, normalise(def, true)]));
      continue;
    }
    if (key === 'properties') {
      out.properties = Object.fromEntries(Object.entries(value).map(([name, prop]) => [name, normalise(prop)]));
      continue;
    }
    if (key === 'prefixItems') {
      out.items = normalise(value);
      out.additionalItems = false;
      continue;
    }
    out[key] = normalise(value);
  }
  return out;
}

export function prepareSchema(raw) {
  const schema = structuredClone(raw);
  for (const [prop, name] of Object.entries(ROOT_UNIONS)) {
    const union = schema.properties?.[prop];
    if (!union) throw new Error(`protocol.schema.json has no root property "${prop}"`);
    if (schema.$defs[name]) throw new Error(`protocol.schema.json already defines "${name}"`);
    schema.$defs[name] = { ...union, title: name };
    schema.properties[prop] = { $ref: `#/$defs/${name}` };
  }
  const prepared = normalise(schema);
  prepared.title = 'ClickyTabsProtocol';
  return prepared;
}

export async function render() {
  const raw = JSON.parse(readFileSync(schemaPath, 'utf8'));
  const ts = await compile(prepareSchema(raw), 'ClickyTabsProtocol', {
    bannerComment: BANNER,
    additionalProperties: false,
    unreachableDefinitions: true,
    strictIndexSignatures: true,
    unknownAny: true,
    format: true,
    style: { singleQuote: true, printWidth: 110, trailingComma: 'all', endOfLine: 'lf' },
  });
  // json2ts tags every definition with a "referenced by ... via the `definition` X" note; it adds nothing here.
  const cleaned = ts
    .replace(/\n \*\n \* This interface was referenced by `ClickyTabsProtocol`'s JSON-Schema\n \* via the `definition` "[^"]+"\.\n/g, '\n')
    .replace(/\/\*\*\n \* This interface was referenced by `ClickyTabsProtocol`'s JSON-Schema\n \* via the `definition` "[^"]+"\.\n \*\/\n/g, '')
    .replace(/\r\n/g, '\n');
  return cleaned.endsWith('\n') ? cleaned : `${cleaned}\n`;
}

async function main() {
  const next = await render();
  const target = relative(process.cwd(), outPath) || outPath;
  if (process.argv.includes('--check')) {
    let current = '';
    try {
      current = readFileSync(outPath, 'utf8').replace(/\r\n/g, '\n');
    } catch {
      // missing file counts as drift
    }
    if (current !== next) {
      console.error(`${target} is stale: run \`npm run gen:protocol\` and commit the result.`);
      process.exit(1);
    }
    console.log(`${target} is up to date`);
    return;
  }
  writeFileSync(outPath, next, 'utf8');
  console.log(`wrote ${target}`);
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  await main();
}
